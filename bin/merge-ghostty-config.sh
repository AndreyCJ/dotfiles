#!/usr/bin/env bash

set -euo pipefail

# Merge the OS-specific Ghostty config (macos.conf on macOS, linux.conf on
# Linux) into the shared config and write the result to ~/.config/ghostty/
# config.ghostty. Ghostty loads config.ghostty before config, so OS-specific
# keys that are not set in the shared config take effect.
#
# config-file includes are stripped from the merged copy: ghostty dedupes
# config-file paths across the whole load and flags a second occurrence as a
# "cycle detected", so includes must live only in the shared config (which
# loads after this file).
#
# Run standalone after editing the ghostty conf files, or via bin/install.sh.

DOTFILES="${DOTFILES:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
DIR="$DOTFILES/ghostty/.config/ghostty"
OUT="$HOME/.config/ghostty/config.ghostty"

case "$(uname -s)" in
  Darwin) PLATFORM="$DIR/macos.conf" ;;
  *)      PLATFORM="$DIR/linux.conf" ;;
esac

{
  printf '# Generated by merge-ghostty-config.sh — do not edit.\n\n'
  grep -vE '^[[:space:]]*config-file' "$DIR/config"
  printf '\n'
  cat "$PLATFORM"
} > "$OUT"

echo "Wrote $OUT"